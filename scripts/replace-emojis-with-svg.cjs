const files = ['templates/js/admin-inline-1.js', 'templates/js/admin-inline-2.js', 'templates/js/admin-inline-4.js'];

console.log('🔄 开始替换表情符号为 SVG...\n');

files.forEach(file => {
  let content = fs.readFileSync(file, 'utf-8');
  let modified = false;
  let replacedCount = 0;

  Object.entries(svgIcons).forEach(([emoji, svg]) => {
    // 替换模板字符串中的表情符号（不用引号包围）
    const regex = new RegExp(emoji, 'g');
    const matches = content.match(regex);
    if (matches) {
      content = content.replace(regex, svg);
      modified = true;
      replacedCount += matches.length;
      console.log(`  ${file}: 替换 ${emoji} (${matches.length} 次)`);
    }
  });

  if (modified) {
    fs.writeFileSync(file, content, 'utf-8');
    console.log(`✓ ${file}: 已更新 (共替换 ${replacedCount} 个表情符号)\n`);
  } else {
    console.log(`  ${file}: 无需修改\n`);
  }
});

